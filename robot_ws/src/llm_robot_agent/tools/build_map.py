#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
离线地图生成（Offline Map Builder）
===================================

两种建图路径
------------
[A] 真机流程（推荐，答辩时用这条）
    roslaunch llm_robot_agent gazebo.launch
    rosrun gmapping slam_gmapping scan:=scan
    rosrun teleop_twist_keyboard teleop_twist_keyboard.py   # 手动走一圈
    rosrun map_server map_saver -f $(rospack find llm_robot_agent)/maps/indoor

    优点：地图带 SLAM 噪声与不完整边缘，是真实的定位挑战。
    缺点：需要有人在场用键盘把机器人开遍每个房间，约 5-10 分钟。

[B] 离线真值地图（本工具，用于开发与回归）
    直接对 worlds/*.world 做光线投射光栅化，生成 PGM + YAML。

    优点：秒级生成，可重复，适合在没有 GUI/没有 ROS 的环境里
          先把导航栈的上下游打通（比如在 Windows 上验证参数）。
    缺点：地图是「完美」的，传感器噪声与建图误差都不存在，
          AMCL 定位会过于容易，不能替代 [A] 作为最终验收依据。

本质区别
--------
[A] 是「机器人扫地感知出来的」，[B] 是「上帝视角直接抄答案」。
两者坐标系一致（都以 world 原点为 map 原点），所以 locations.yaml
的坐标可以通用。

用法
----
    python3 tools/build_map.py --world worlds/complex_indoor.world \\
            --out maps/indoor --resolution 0.05

产出：
    maps/indoor.pgm   —— 占据栅格图（ROS map_server 格式）
    maps/indoor.yaml  —— 元数据
"""

from __future__ import annotations

import argparse
import math
import os
import sys

# 复用审计工具的几何解析，避免两套解析逻辑
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from audit_world import parse_world  # noqa: E402


def rasterize(obstacles, resolution: float,
              margin: float = 1.0,
              robot_zmin: float = 0.05, robot_zmax: float = 1.2):
    """把障碍体光栅化成占据栅格。

    返回 (grid, origin_x, origin_y)，grid[j][i] 取值：
        0   = 自由（可通行）
        100 = 占据
        205 = 未知（地图外边界）
    """
    xs, ys = [], []
    for o in obstacles:
        if not o.overlaps_robot(robot_zmin, robot_zmax):
            continue
        xs += [o.cx - o.hx, o.cx + o.hx]
        ys += [o.cy - o.hy, o.cy + o.hy]
    if not xs:
        raise ValueError("world 中没有可用障碍体")

    x0 = min(xs) - margin
    y0 = min(ys) - margin
    x1 = max(xs) + margin
    y1 = max(ys) + margin

    w = int(math.ceil((x1 - x0) / resolution))
    h = int(math.ceil((y1 - y0) / resolution))

    # 205 = 未知，外圈保持未知；内部先全部填自由，再打障碍
    grid = [[205] * w for _ in range(h)]

    # 简单做法：整个 bounding box 内都算已知区域
    for j in range(h):
        for i in range(w):
            grid[j][i] = 0

    for o in obstacles:
        if not o.overlaps_robot(robot_zmin, robot_zmax):
            continue
        if o.kind == "cylinder":
            ri = int(math.ceil((o.hx + resolution) / resolution))
            ci = int((o.cx - x0) / resolution)
            cj = int((o.cy - y0) / resolution)
            r2 = (o.hx / resolution) ** 2
            for dj in range(-ri, ri + 1):
                for di in range(-ri, ri + 1):
                    if di * di + dj * dj <= r2:
                        ii, jj = ci + di, cj + dj
                        if 0 <= ii < w and 0 <= jj < h:
                            grid[jj][ii] = 100
        else:
            i0 = int((o.cx - o.hx - x0) / resolution)
            i1 = int((o.cx + o.hx - x0) / resolution)
            j0 = int((o.cy - o.hy - y0) / resolution)
            j1 = int((o.cy + o.hy - y0) / resolution)
            for jj in range(max(0, j0), min(h, j1 + 1)):
                for ii in range(max(0, i0), min(w, i1 + 1)):
                    grid[jj][ii] = 100

    return grid, x0, y0


def grid_to_pixel(v: int) -> int:
    """把内部占据值（0/100/205）换成 ROS map 的 PGM 像素亮度。

    ROS map_server 用 occupied = (255 - pixel) / 255 还原占据概率，
    配合 occupied_thresh 0.65 / free_thresh 0.196：
        占据 (occ=1.00)  -> pixel 0    （黑）
        自由 (occ=0.00)  -> pixel 254  （白）
        未知 (occ=0.80)  -> pixel 205  （灰）  ← ROS 里 >=0.65 仍判为占据，
                                                  所以未知要单独用 205 表示

    grid 里的 0/100/205 是「百分比占据」语义，不能直接写进 PGM；
    直接写会让自由区变成纯黑（占据）、墙变成灰白（自由），地图整体反向。
    """
    return {
        0: 254,       # 自由 -> 白
        100: 0,       # 占据 -> 黑
        205: 205,     # 未知 -> 灰
    }.get(v, 205 if v > 100 else 254)


def write_pgm(path: str, grid) -> None:
    """写二进制 PGM（P5）。

    注意两件事，任何一件做错都会让整张地图黑白颠倒：

    1) PGM 行序是「从上到下」，而 ROS 的 map 原点在**左下角**，
       所以写入时要垂直翻转。

    2) ★ 内部 grid 用的是「0=自由 / 100=占据 / 205=未知」这种
       "占据概率"语义，但 PGM 像素是「亮度」语义，两者正好相反：
           PGM 0   （黑） = 占据
           PGM 254/255（白） = 自由
           PGM 205 （灰） = 未知
       ROS map_server 读图时是按 (255 - pixel) / 255 还原占据概率的，
       所以这里必须做 255- 反转。原实现直接把 grid 的 0/100 写进
       PGM，导致自由空间被写成黑色（= 占据），墙被写成白色（= 自由），
       整张地图完全反向：
         - AMCL 认为机器人在墙里，粒子云乱飞
         - move_base 全局代价值到处是 100/0 反转，
           任何目标点都 "a valid plan could not be found"
       PGM 只有 0 和 100 两种值、没有 255，就是漏了这一步的特征。
    """
    h = len(grid)
    w = len(grid[0])
    with open(path, "wb") as f:
        f.write(b"P5\n")
        f.write(f"# generated by tools/build_map.py\n".encode())
        f.write(f"{w} {h}\n".encode())
        f.write(b"255\n")
        buf = bytearray()
        for j in range(h - 1, -1, -1):      # 翻转：从上到下
            buf.extend(bytes(grid_to_pixel(v) for v in grid[j]))
        f.write(bytes(buf))


def write_yaml(path: str, pgm_name: str, resolution: float,
               origin_x: float, origin_y: float) -> None:
    # ROS map 的 origin 是栅格图左下角在世界坐标中的位置
    text = (
        f"image: {pgm_name}\n"
        f"resolution: {resolution}\n"
        f"origin: [{origin_x:.4f}, {origin_y:.4f}, 0.000000]\n"
        f"negate: 0\n"
        f"occupied_thresh: 0.65\n"
        f"free_thresh: 0.196\n"
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main() -> int:
    ap = argparse.ArgumentParser(description="从 world 生成 ROS 地图")
    ap.add_argument("--world", required=True)
    ap.add_argument("--out", required=True, help="输出前缀，如 maps/indoor")
    ap.add_argument("--resolution", type=float, default=0.05)
    ap.add_argument("--margin", type=float, default=1.0)
    args = ap.parse_args()

    if not os.path.exists(args.world):
        print(f"错误：world 不存在 {args.world}", file=sys.stderr)
        return 2

    obstacles, warnings = parse_world(args.world)
    grid, ox, oy = rasterize(obstacles, args.resolution, args.margin)

    out_dir = os.path.dirname(os.path.abspath(args.out))
    os.makedirs(out_dir, exist_ok=True)
    base = os.path.basename(args.out)

    pgm_path = os.path.join(out_dir, base + ".pgm")
    yaml_path = os.path.join(out_dir, base + ".yaml")
    write_pgm(pgm_path, grid)
    write_yaml(yaml_path, base + ".pgm", args.resolution, ox, oy)

    h, w = len(grid), len(grid[0])
    occ = sum(row.count(100) for row in grid)
    print(f"已生成 {pgm_path}")
    print(f"  尺寸 {w} x {h} 格 | 分辨率 {args.resolution} m")
    print(f"  世界范围 x[{ox:.2f}, {ox + w * args.resolution:.2f}] "
          f"y[{oy:.2f}, {oy + h * args.resolution:.2f}]")
    print(f"  占据格 {occ}（{occ * args.resolution ** 2:.1f} m²）")
    print(f"已生成 {yaml_path}")
    if warnings:
        print(f"  {len(warnings)} 条几何告警（见 audit_world.py）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
